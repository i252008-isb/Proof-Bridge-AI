"""ProofBridge AI: AI-powered customer support & refund investigation.

Central principle: customers submit the proof, ProofBridge AI investigates
the proof, human support agents make the final decisions.

Public API (the backend integration surface):
    extract_document, extract_ticket_claims, extract_evidence,
    extract_evidence_batch, analyze_visual_evidence, extract_refund_policy,
    compare_support_evidence, analyze_support_case,
    arun_support_case_analysis, generate_investigation_report

All errors raised by this package derive from ProofBridgeAIError. The AI
module never issues, rejects, or transfers payments and never creates
database records.
"""

